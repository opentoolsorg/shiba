#!/usr/bin/env node
/** Generate docs/SECRETS.md; --check reports .dev.vars.example name drift (no file edits). */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const paths = {
  manifest: resolve(root, "apps/backend/worker-secrets.json"),
  schema: resolve(root, "apps/backend/worker-secrets.schema.json"),
  envSchema: resolve(root, ".env.schema"),
  example: resolve(root, "apps/backend/.dev.vars.example"),
  out: resolve(root, process.argv.find((a) => a.startsWith("--out="))?.slice(6) ?? "docs/SECRETS.md"),
};
const check = process.argv.includes("--check");

const exampleKeys = (text) => {
  const s = new Set();
  for (const line of text.split("\n")) {
    const m = line.match(/^(?:#\s*)?([A-Z][A-Z0-9_]+)=/);
    if (m) s.add(m[1]);
  }
  return s;
};

const cleanPurpose = (raw) =>
  raw
    .replace(/\s*@\S+/g, "")
    .replace(/\s+/g, " ")
    .trim();

const commentDocs = (text, keyed = /^([A-Z][A-Z0-9_]+)=/) => {
  const docs = new Map();
  let section = "Worker deploy";
  let buf = [];
  const note = (key, required = false) => {
    const purpose = cleanPurpose(buf.join(" "));
    if (purpose) docs.set(key, { section, purpose, required });
    buf = [];
  };
  for (const line of text.split("\n")) {
    if (/^#\s*---/.test(line)) {
      section = line.replace(/^#\s*---\s*|\s*-{3,}\s*$/g, "").trim() || section;
      buf = [];
      continue;
    }
    const ex = line.match(/^#\s*([A-Z][A-Z0-9_]+)=/);
    if (ex) {
      note(ex[1], /@required\b/.test(buf.join("\n")));
      continue;
    }
    if (line.startsWith("#")) {
      const body = line.slice(1).trim();
      if (body && !/^Copy to /.test(body)) buf.push(body);
    } else {
      const m = line.match(keyed);
      if (m) note(m[1], /@required\b/.test([...buf, line].join("\n")));
      else if (!line.trim()) buf = [];
    }
  }
  return docs;
};

const schemaDocs = (schema) => {
  const raw = schema?.secretDescriptions ?? schema?.definitions ?? {};
  const out = new Map();
  for (const [name, meta] of Object.entries(raw)) {
    if (!meta || typeof meta !== "object") continue;
    out.set(name, {
      purpose: cleanPurpose(meta.description ?? "") || "undocumented",
      required: Boolean(meta.required),
      section: meta.feature ?? meta.section ?? "Worker deploy",
    });
  }
  return out;
};

const FEATURE_RULES = [
  [/^GITHUB_/, "GitHub clone, PR publish, App installs, or webhooks"],
  [/^SLACK_/, "Slack approvals, installs, and channel routing"],
  [/^TELEGRAM_/, "Telegram bot webhook lane"],
  [/^DISCORD_/, "Discord interactions lane"],
  [/^LINEAR_/, "Linear agent sessions and webhooks"],
  [/^BETTER_AUTH_/, "Built-in dashboard email/social sign-in"],
  [/^MCP_OAUTH_/, "Vendor MCP OAuth client registration"],
  [/^OPEN_CONNECTOR_/, "OpenConnector integrations and read gateway"],
  [/^FOUNDER_/, "Native founder reads (Stripe, Meta, HubSpot)"],
  [/^GMAIL_/, "Gmail read-only connection"],
  [/^GOOGLE_ANTIGRAVITY_/, "Antigravity / Gemini Providers card"],
  [/^MODEL_CREDENTIAL_/, "Dashboard Providers per-user OAuth storage"],
  [/SUBSCRIPTION/, "Deployment-wide subscription harness lane"],
  [/^AI_GATEWAY_/, "AI Gateway authorization on egress"],
  [/^LOCAL_ADAPTER_|^PAIRING_/, "Shiba Desktop local runtime and pairing"],
  [/^INTERNAL_SIGNING_|^ARTIFACT_SIGNING_/, "Signed intake headers and artifact downloads"],
  [/^TRIGGER_/, "POST /api/trigger automation ingress"],
  [/^TYPESAFE_/, "TypeSafe automation run_when"],
  [/^WEB_SEARCH_/, "Configured web search provider calls"],
  [/^DASHBOARD_APPROVERS/, "Shared dashboard approval resolution"],
];

const featureBreak = (name, section, purpose) => {
  for (const [re, label] of FEATURE_RULES) if (re.test(name)) return label;
  const hit = purpose.match(/([A-Za-z][^.]{8,80}(lane|webhook|route))/i);
  return hit?.[1] ?? section ?? "Optional operator configuration";
};

const rowFor = (name, env, ex, meta) => {
  const hit = meta.get(name) ?? env.get(name) ?? ex.get(name);
  const purpose = hit?.purpose?.trim() || "undocumented";
  return {
    name,
    required: hit?.required ? "required" : "optional",
    purpose,
    feature: featureBreak(name, hit?.section, purpose),
  };
};

const manifest = JSON.parse(readFileSync(paths.manifest, "utf8"));
const schema = JSON.parse(readFileSync(paths.schema, "utf8"));
const env = commentDocs(readFileSync(paths.envSchema, "utf8"));
const ex = commentDocs(readFileSync(paths.example, "utf8"));
const meta = schemaDocs(schema);
const esc = (s) => s.replace(/\|/g, "\\|");
const rows = [...manifest.secrets].sort().map((n) => rowFor(n, env, ex, meta));
const body = [
  "# Worker secrets reference",
  "",
  "Generated by `node scripts/secrets-doc.mjs` from `apps/backend/worker-secrets.json`.",
  "Lists binding **names** only; never store values in git.",
  "",
  "| Name | Required | Purpose | Feature affected if unset |",
  "| --- | --- | --- | --- |",
  ...rows.map((r) => `| \`${r.name}\` | ${r.required} | ${esc(r.purpose)} | ${esc(r.feature)} |`),
  "",
].join("\n");
writeFileSync(paths.out, body);

if (check) {
  const exKeys = exampleKeys(readFileSync(paths.example, "utf8"));
  const want = new Set(rows.map((r) => r.name));
  const missing = rows.filter((r) => !exKeys.has(r.name)).map((r) => r.name);
  const extra = [...exKeys].filter((k) => !want.has(k)).sort();
  if (missing.length || extra.length) {
    console.log("secrets-doc --check: drift vs apps/backend/.dev.vars.example");
    for (const k of missing) console.log(`  missing from example: ${k}`);
    for (const k of extra) console.log(`  extra in example (not in worker-secrets.json): ${k}`);
    process.exitCode = 1;
  } else console.log("secrets-doc --check: example names match worker-secrets.json");
} else console.log(`secrets-doc: wrote ${paths.out} (${rows.length} secrets)`);