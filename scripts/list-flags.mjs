#!/usr/bin/env node
import { readdir, readFile, writeFile, stat } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const docPath = join(root, "docs/FLAGS.md");
const checkOnly = process.argv.includes("--check");
const FLAG = "SHIBA_[A-Z0-9_]+";
const EXT = /\.(ts|tsx|js|jsx|mjs|cjs)$/;
const DOT_READ = new RegExp(
  String.raw`(?:\b(?:process\.env|import\.meta\.env)(?:\.(${FLAG})|\[['"](${FLAG})['"]\])|\b(?:env|this\.env|ctx\.env)\??\.(${FLAG})|\b(?:env|this\.env|ctx\.env)\[(?:['"](${FLAG})['"]|([A-Z][A-Z0-9_]*))\])`,
  "g",
);
const CAST_READ = new RegExp(String.raw`process\.env[^;\n]*\b(${FLAG})\b`, "g");
const ALIAS = /export const ([A-Z][A-Z0-9_]*) = "(SHIBA_[A-Z0-9_]+)"/g;

const exists = async (path) => {
  try {
    await stat(path);
    return true;
  } catch {
    return false;
  }
};

async function scanRoots() {
  const roots = ["apps/backend/src", "apps/frontend/src"];
  for (const name of await readdir(join(root, "packages"))) {
    const src = join(root, "packages", name, "src");
    if (await exists(src)) roots.push(relative(root, src));
  }
  return roots;
}

async function walk(dir, out = []) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) await walk(path, out);
    else if (EXT.test(entry.name)) out.push(path);
  }
  return out;
}

function inferDefault(line) {
  const nullish = line.match(/\?\?\s*(['"])([^'"]+)\1|\?\?\s*([A-Z][A-Z0-9_]+)/);
  if (nullish) return nullish[2] ?? `constant ${nullish[3]}`;
  const orLit = line.match(/\|\|\s*(['"])([^'"]+)\1/);
  if (orLit) return orLit[2];
  if (/!==\s*["']0["']/.test(line)) return "on unless set to 0";
  if (/===\s*["']1["']/.test(line)) return "off unless set to 1";
  if (/===\s*["']0["']/.test(line)) return "unset allows; 0 disables";
  if (/===\s*["']true["']/.test(line)) return "off unless true";
  return "unclear";
}

async function wranglerSets() {
  const configs = new Map();
  const strip = (text) => text.replace(/\/\*[\s\S]*?\*\/|\/\/[^\n]*/g, "");
  for (const name of await readdir(join(root, "apps/backend"))) {
    if (!/^wrangler.*\.jsonc$/.test(name)) continue;
    const raw = await readFile(join(root, "apps/backend", name), "utf8");
    for (const m of strip(raw).matchAll(new RegExp(`"(${FLAG})"\\s*:\\s*"([^"]*)"`, "g"))) {
      if (!configs.has(m[1])) configs.set(m[1], []);
      const row = `${name}=${m[2] === "" ? "(empty)" : m[2]}`;
      if (!configs.get(m[1]).includes(row)) configs.get(m[1]).push(row);
    }
  }
  return configs;
}

async function buildDoc() {
  const aliases = new Map();
  const sites = new Map();
  const filesText = new Map();
  const files = [];
  for (const rel of await scanRoots()) files.push(...(await walk(join(root, rel))));
  const add = (flag, file, line) => {
    if (!sites.has(flag)) sites.set(flag, new Set());
    sites.get(flag).add(`${relative(root, file)}:${line}`);
  };
  for (const file of files) {
    const text = await readFile(file, "utf8");
    filesText.set(file, text.split("\n"));
    for (const m of text.matchAll(ALIAS)) aliases.set(m[1], m[2]);
  }
  for (const file of files) {
    const text = filesText.get(file).join("\n");
    text.split("\n").forEach((line, i) => {
      const n = i + 1;
      for (const m of line.matchAll(DOT_READ)) {
        const flag = m[1] ?? m[2] ?? m[3] ?? m[4] ?? aliases.get(m[5] ?? "");
        if (flag?.startsWith("SHIBA_")) add(flag, file, n);
      }
      for (const m of line.matchAll(CAST_READ)) add(m[1], file, n);
    });
  }
  const defaults = new Map();
  for (const [flag, locs] of sites) {
    const hints = new Set();
    for (const loc of locs) {
      const sep = loc.lastIndexOf(":");
      const lines = filesText.get(join(root, loc.slice(0, sep)));
      const d = inferDefault(lines?.[Number(loc.slice(sep + 1)) - 1] ?? "");
      if (d !== "unclear") hints.add(d);
    }
    defaults.set(flag, hints.size ? [...hints].join("; ") : "unclear");
  }
  const configs = await wranglerSets();
  const flags = [...sites.keys()].sort();
  const rows = flags.map((flag) => {
    const locs = [...sites.get(flag)].sort().join(", ");
    const cfg = (configs.get(flag) ?? []).join(", ") || "—";
    return `| \`${flag}\` | ${locs} | ${defaults.get(flag)} | ${cfg} |`;
  });
  return [
    "# SHIBA deployment flags",
    "",
    `Generated by \`node scripts/list-flags.mjs\`. **${flags.length}** flags with env reads under \`apps/backend/src\`, \`apps/frontend/src\`, and \`packages/*/src\`.`,
    "",
    "| Flag | Reads | Default when unset | Set in wrangler\\*.jsonc |",
    "| --- | --- | --- | --- |",
    ...rows,
    "",
  ].join("\n");
}

const doc = await buildDoc();
if (checkOnly) {
  let onDisk = "";
  try {
    onDisk = await readFile(docPath, "utf8");
  } catch {
    console.error("docs/FLAGS.md is missing; run without --check to generate.");
    process.exit(1);
  }
  if (onDisk !== doc) {
    console.error("docs/FLAGS.md is stale; run: pnpm flags:doc");
    process.exit(1);
  }
  console.log("docs/FLAGS.md is up to date.");
  process.exit(0);
}
await writeFile(docPath, doc);
console.log(`Wrote ${docPath}`);