import { readFileSync,writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
const root=new URL("../",import.meta.url),files=["src/types.ts","src/json.ts","src/operations.ts","src/manifest.ts","src/gateway.ts","src/callback.ts","src/index.ts","src/upstream-adapter.ts","../../infra/openconnector-read-gateway.mjs"];
const sha=body=>createHash("sha256").update(body).digest("hex");
const sources=files.map(file=>({file,sha256:sha(readFileSync(new URL(file,root)))}));
const content=`/** Generated by scripts/generate-manifest.mjs; changes require a new operator-reviewed manifest/version pin. */\nexport const BUILD_DIGEST = ${JSON.stringify(sha(JSON.stringify(sources)))};\nexport const EXECUTOR_DIGEST = ${JSON.stringify(sources.find(row=>row.file==="src/operations.ts").sha256)};\n`;
const target=new URL("src/generated.ts",root);
if(process.argv.includes("--check")){if(readFileSync(target,"utf8")!==content)throw new Error("Read gateway source manifest is stale");}
else writeFileSync(fileURLToPath(target),content);
