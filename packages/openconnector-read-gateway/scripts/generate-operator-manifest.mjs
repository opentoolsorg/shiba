import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
const files = ["coordinated-owner.ts", "operator-envelope.ts", "operator-gateway.ts", "operator-provider.ts", "operator-store.ts", "operator-upstream.ts"];
const sources = Object.fromEntries(files.map(file => [file, createHash("sha256").update(readFileSync(new URL(`../src/${file}`, import.meta.url))).digest("hex")]));
const content = `// Generated by scripts/generate-operator-manifest.mjs. Never hash credentials.\nexport const OPERATOR_SOURCE_HASHES = ${JSON.stringify(sources, null, 2)} as const;\n`;
const target = new URL("../src/operator-manifest.generated.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== content) throw new Error("Operator source manifest is stale");
} else writeFileSync(target, content);
