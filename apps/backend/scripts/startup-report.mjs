#!/usr/bin/env node
/** Offline startup CPU report → docs/STARTUP-CPU.md */
import { createRequire } from "node:module";
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const backendRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(backendRoot, "../..");
const outRoot = join(backendRoot, ".wrangler/startup-report");
mkdirSync(outRoot, { recursive: true });
const bundle = join(outRoot, "worker.bundle");
const metafile = join(outRoot, "bundle-meta.json");
const mapFile = join(outRoot, "index.js.map");
const profile = join(outRoot, "worker-startup.cpuprofile");
const docOut = resolve(repoRoot, process.argv[2] ?? "docs/STARTUP-CPU.md");

const wrangler = (args) => {
  const r = spawnSync("pnpm", ["exec", "wrangler", ...args], {
    cwd: backendRoot,
    encoding: "utf8",
    env: { ...process.env, WRANGLER_SEND_METRICS: "false" },
  });
  if (r.status !== 0) throw new Error((r.stderr || r.stdout || "wrangler failed").trim().slice(-800));
  return `${r.stdout ?? ""}\n${r.stderr ?? ""}`;
};

wrangler([
  "deploy",
  "--dry-run",
  `--config=${join(backendRoot, "wrangler.jsonc")}`,
  "--containers-rollout",
  "none",
  `--outfile=${bundle}`,
  `--outdir=${outRoot}`,
  `--metafile=${metafile}`,
]);

let startupLog = "";
let profileOk = false;
try {
  startupLog = wrangler(["check", "startup", `--workerBundle=${bundle}`, `--outfile=${profile}`, `--config=${join(backendRoot, "wrangler.jsonc")}`]);
  profileOk = true;
} catch {
  startupLog = "(wrangler check startup failed; no local CPU profile)";
}

const req = createRequire(join(backendRoot, "package.json"));
const { TraceMap, originalPositionFor } = req(
  req.resolve("@jridgewell/trace-mapping", { paths: [req.resolve("wrangler")] }),
);

const meta = JSON.parse(readFileSync(metafile, "utf8"));
const sizes = Object.entries(meta.inputs ?? {})
  .map(([k, v]) => ({ path: k.replace(/^\.\.\/\.\.\//, ""), bytes: v.bytesInOutput ?? v.bytes ?? 0 }))
  .filter((r) => r.bytes > 0)
  .sort((a, b) => b.bytes - a.bytes);

const trace = profileOk ? new TraceMap(JSON.parse(readFileSync(mapFile, "utf8"))) : null;
const evalMs = new Map();
if (profileOk) {
  const prof = JSON.parse(readFileSync(profile, "utf8"));
  const nodes = new Map(prof.nodes.map((n) => [n.id, n]));
  for (let i = 0; i < prof.samples.length; i++) {
    const cf = nodes.get(prof.samples[i])?.callFrame ?? {};
    let file = "";
    if ((cf.functionName ?? "").startsWith("src/")) file = cf.functionName;
    else if (cf.url?.includes("index.js") && cf.lineNumber > 0 && trace) {
      const pos = originalPositionFor(trace, { line: cf.lineNumber, column: cf.columnNumber ?? 0 });
      if (pos.source) file = pos.source.replace(/^\.\.\//, "");
    }
    if (!file) continue;
    evalMs.set(file, (evalMs.get(file) ?? 0) + (prof.timeDeltas[i] ?? 0));
  }
}
const evalRank = [...evalMs.entries()].sort((a, b) => b[1] - a[1]);

const sideEffects = [];
for (const line of readFileSync(join(backendRoot, "src/index.ts"), "utf8").split("\n")) {
  if (/^\s/.test(line)) continue;
  const t = line.trim();
  if (/^import\s+["'][^"']+["']\s*;/.test(t)) sideEffects.push(`index.ts: ${t}`);
  if (/^(?:const|export\s+const)\s+\w+.*=\s*new\s+(?:Set|Map)\(/.test(t)) sideEffects.push(`index.ts: ${t.slice(0, 100)}…`);
  if (/^[a-zA-Z_$][\w$]*\(\)\s*;/.test(t)) sideEffects.push(`index.ts: ${t}`);
}
const shortPath = (p) => p.replace(repoRoot + "/", "").replace(/^\/agent\/repos\/shiba\//, "");

const bundleBytes = statSync(bundle).size;
const fmtKiB = (n) => `${(n / 1024).toFixed(1)} KiB`;
const fmtMs = (us) => `${(us / 1000).toFixed(1)} ms`;
const lines = [
  "# Worker startup CPU report",
  "",
  `Generated by \`node apps/backend/scripts/startup-report.mjs\` on ${new Date().toISOString().slice(0, 10)} (offline dry-run; no deploy).`,
  "",
  "## Bundle",
  "",
  `| Metric | Value |`,
  `| --- | --- |`,
  `| Worker bundle file | ${fmtKiB(bundleBytes)} (\`${relative(repoRoot, bundle)}\`) |`,
  `| Sum of esbuild \`bytesInOutput\` | ${fmtKiB(sizes.reduce((s, r) => s + r.bytes, 0))} |`,
  "",
  ...startupLog
    .split("\n")
    .filter((l) => l.startsWith("│") && (l.includes("KiB") || l.includes("Active:") || l.includes("Profile window")))
    .map((l) => l.replace(/^│\s*/, "")),
  "",
  "## Heaviest modules (esbuild output bytes)",
  "",
  "| Rank | Module | Size |",
  "| ---: | --- | ---: |",
  ...sizes.slice(0, 15).map((r, i) => `| ${i + 1} | \`${r.path}\` | ${fmtKiB(r.bytes)} |`),
  "",
  "## Heaviest modules (local startup evaluation)",
  "",
  "Measured with `wrangler check startup` on this machine; Cloudflare edge timing will differ.",
  "",
  "| Rank | Module | Eval time (sampled) |",
  "| ---: | --- | ---: |",
  ...(evalRank.length
    ? evalRank.slice(0, 15).map(([p, us], i) => `| ${i + 1} | \`${shortPath(p)}\` | ${fmtMs(us)} |`)
    : ["| — | (no profile) | — |"]),
  "",
  "## Top-level side effects",
  "",
  ...sideEffects.slice(0, 25).map((s) => `- ${s}`),
  "",
  "## Recommendations",
  "",
  "1. Keep rarely used HTTP and cron handlers on `await import()` at the call site in `src/index.ts` (founder routes, v1, collaboration, team-model, inbound email) instead of adding static imports.",
  "2. Defer `registerWebhookQueueConsumers()` until the first queue batch or first `/api/*` request so queue wiring is not part of cold start.",
  "3. Replace static `import \"./email/delivery.js\"` and `import \"./knowledge/knowledge-ingest-queue.js\"` with lazy loads inside the handlers that need them.",
  "4. Trim dependency weight: `just-bash`, full `ai` / `@ai-sdk/*`, `effect` Schema, and duplicate `zod` copies dominate bytes and samples — gate sandbox shell helpers and provider adapters behind dynamic import.",
  ...(sizes.some((s) => s.path.includes("vitest"))
    ? [
        "5. Investigate why `vitest` appears in the production metafile (dev graph leak); it should not ship in the Worker bundle.",
      ]
    : [
        "5. Add `wrangler deploy --minify` to CI preview jobs when upload validation flirts with error 10021; minify shrinks parse cost on the edge.",
      ]),
  "",
];

writeFileSync(docOut, lines.join("\n"));
console.log(`Wrote ${relative(repoRoot, docOut)} (${sizes.length} inputs, profile=${profileOk})`);